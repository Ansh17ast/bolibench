async def generate_single_tts(text: str, voice: str, out_wav_path: Path) -> None:
    """Generates speech via Edge-TTS and converts to 16 kHz mono linear PCM WAV via ffmpeg."""
    temp_mp3 = out_wav_path.with_suffix(".temp.mp3")
    try:
        communicate = edge_tts.Communicate(text, voice)
        await communicate.save(str(temp_mp3))
        # Convert to strict 16 kHz, mono, signed 16-bit PCM WAV
        cmd = [
            "ffmpeg",
            "-y",
            "-i",
            str(temp_mp3),
            "-ar",
            "16000",
            "-ac",
            "1",
            "-c:a",
            "pcm_s16le",
            str(out_wav_path),
        ]
        res = subprocess.run(cmd, check=True, capture_output=True)
    finally:
        if temp_mp3.exists():
            temp_mp3.unlink()


def apply_acoustic_transformation(in_wav: Path, out_wav: Path, filter_params: str) -> None:
    """Applies ffmpeg audio transformation filter (e.g. tempo change, bandpass, room reverb)."""
    cmd = [
        "ffmpeg",
        "-y",
        "-i",
        str(in_wav),
        "-filter:a",
        filter_params,
        "-ar",
        "16000",
        "-ac",
        "1",
        "-c:a",
        "pcm_s16le",
        str(out_wav),
    ]
    subprocess.run(cmd, check=True, capture_output=True)


async def build_dataset() -> None:
    """Builds all 50 pairs, validates audio, and writes benchmark_manifest.json."""
    BENCHMARK_AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    validator = AudioValidator()

    manifest_items: List[BatchManifestItem] = []

    logger.info("Building 50-pair benchmark dataset across 6 categories...")

    for spec in PAIRS_SPECIFICATION:
        pair_id = spec["pair_id"]
        source_type = spec["source_type"]
        wav_a = BENCHMARK_AUDIO_DIR / f"{pair_id}_a.wav"
        wav_b = BENCHMARK_AUDIO_DIR / f"{pair_id}_b.wav"

        logger.info(f"Processing [{pair_id}] ({spec['category']}, {source_type.value})...")

        if source_type == AudioSourceType.HUMAN_RECORDED:
            src_a = LOCAL_TEST_AUDIO_DIR / spec["existing_audio_a"]
            src_b = LOCAL_TEST_AUDIO_DIR / spec["existing_audio_b"]
            if not src_a.exists() or not src_b.exists():
                raise FileNotFoundError(f"Missing source audio for {pair_id}: {src_a} / {src_b}")
            shutil.copyfile(src_a, wav_a)
            shutil.copyfile(src_b, wav_b)

        elif source_type == AudioSourceType.TTS_SYNTHETIC:
            voice = spec["voice"]
            if not wav_a.exists():
                await generate_single_tts(spec["reference_transcript_a"], voice, wav_a)
            if not wav_b.exists():
                await generate_single_tts(spec["reference_transcript_b"], voice, wav_b)

        elif source_type == AudioSourceType.ACOUSTIC_TRANSFORMED:
            source_pair_id = spec["source_pair_id"]
            src_a = BENCHMARK_AUDIO_DIR / f"{source_pair_id}_a.wav"
            src_b = BENCHMARK_AUDIO_DIR / f"{source_pair_id}_b.wav"
            params = spec["transformation_params"]
            apply_acoustic_transformation(src_a, wav_a, params)
            apply_acoustic_transformation(src_b, wav_b, params)

        # Validate both WAV files immediately
        validator.validate_live_audio(wav_a.name, wav_a.read_bytes())
        validator.validate_live_audio(wav_b.name, wav_b.read_bytes())

        # Construct Manifest Item with relative audio paths
        rel_path_a = str(wav_a.relative_to(WORKSPACE_DIR)).replace("\\", "/")
        rel_path_b = str(wav_b.relative_to(WORKSPACE_DIR)).replace("\\", "/")

        item = BatchManifestItem(
            pair_id=pair_id,
            category=spec["category"],
            language_code=spec["language_code"],
            audio_condition="clean_recorded" if source_type != AudioSourceType.ACOUSTIC_TRANSFORMED else "acoustic_transformed",
            source_type=source_type,
            audio_path_a=rel_path_a,
            audio_path_b=rel_path_b,
            reference_transcript_a=spec["reference_transcript_a"],
            reference_transcript_b=spec["reference_transcript_b"],
            expected_critical_fields_a=spec.get("expected_critical_fields_a", {}),
            expected_critical_fields_b=spec.get("expected_critical_fields_b", {}),
            expected_intent_a=spec.get("expected_intent_a"),
            expected_intent_b=spec.get("expected_intent_b"),
            expected_action_a=spec.get("expected_action_a"),
            expected_action_b=spec.get("expected_action_b"),
            distinction_field=spec.get("distinction_field"),
            description=spec.get("description"),
            speaker_metadata={"voice": spec.get("voice"), "notes": spec.get("notes")},
            tts_voice_or_source=spec.get("tts_voice_or_source"),
            transformation_params=spec.get("transformation_params"),
            dataset_version="1.0.0",
            notes=spec.get("notes"),
        )
        manifest_items.append(item)

    manifest = BatchManifest(
        manifest_version="1.1.0",
        name="BoliBench 50-Pair Contrast Evaluation Benchmark",
        description="Audited 50-pair speech contrast benchmark across 6 semantic categories (v1.1.0: repaired bench_ent_001 with bench_ent_001_v2)",
        created_at=datetime.now(timezone.utc).isoformat(),
        items=manifest_items,
    )

    save_manifest(manifest, MANIFEST_PATH)
    logger.info(f"Manifest written successfully to: {MANIFEST_PATH}")

    # Validate the full manifest
    report = validate_manifest(manifest, base_dir=WORKSPACE_DIR, audio_validator=validator)
    logger.info(f"Manifest validation: total={report.total_items}, ready={report.ready_count}, invalid={len(report.invalid_items)}")
    logger.info(f"Category counts: {report.counts_by_category}")
    logger.info(f"Source provenance counts: {report.counts_by_source}")


if __name__ == "__main__":
    asyncio.run(build_dataset())
